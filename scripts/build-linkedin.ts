/**
 * Generate `docs/linkedin.md` — copy-paste blocks for Amna's LinkedIn profile.
 *
 * Generated from the same profile as the site and the CV for one reason: a recruiter opens the
 * LinkedIn profile with the CV already on screen. Dates that disagree, a job title worded
 * differently, a project credited one way here and another way there — each reads as
 * carelessness, and for an architect it reads as carelessness about credit.
 *
 * LinkedIn has no usable API for this, so the output is paste-ready rather than automated.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { absoluteUrl, SITE_URL_IS_PLACEHOLDER } from '../src/config/site';
import { artifactDirs } from '../src/lib/files';
import {
  formatPeriod,
  loadProfile,
  oneLine,
  orderedExperience,
  publishedProjects,
  PROJECT_ROOT,
} from '../src/lib/profile';
import { valueOf } from '../src/schema/claim';

/** LinkedIn's headline limit. */
const HEADLINE_LIMIT = 220;

function main(): void {
  const profile = loadProfile();
  const { person } = profile;
  const siteUrl = SITE_URL_IS_PLACEHOLDER
    ? '(portfolio URL — set once the GitHub username is known)'
    : absoluteUrl('/');
  const software = profile.software.flatMap((g) => g.items);

  const headlines = profile.variants.slice(0, 3).map((variant) => {
    const keywords = variant.keywords.slice(0, 3).join(' · ');
    return `${variant.headline} | ${keywords} | ${person.location.city}`;
  });

  const about = [
    oneLine(person.statement),
    ...profile.about.map(oneLine),
    `Software: ${software.join(', ')}.`,
    oneLine(person.availability),
    `Portfolio: ${siteUrl}`,
  ].join('\n\n');

  const roles = orderedExperience(profile)
    .map((role) =>
      [
        `### ${role.title} — ${role.organisation}`,
        '',
        `**Dates:** ${formatPeriod(role)}  `,
        `**Location:** ${valueOf(role.location) ?? '(confirm)'}`,
        '',
        oneLine(role.summary),
        '',
        role.highlights.map((h) => `- ${oneLine(h.text)}`).join('\n'),
      ].join('\n'),
    )
    .join('\n\n');

  const projects = publishedProjects(profile)
    .map((project) => {
      const role = valueOf(project.role);
      return [
        `### ${project.title}`,
        '',
        `**Associated with:** ${project.organisation}  `,
        `**Dates:** ${valueOf(project.period) ?? '(confirm)'}  `,
        `**Link:** ${SITE_URL_IS_PLACEHOLDER ? '(project URL once the site is live)' : absoluteUrl(`/projects/${project.id}`)}`,
        '',
        // Credits are written as a sentence in the profile; strip its full stop before adding one.
        `${oneLine(project.summary)}${role ? ` Role: ${role}.` : ''}${project.credits ? ` ${oneLine(project.credits).replace(/\.$/, '')}.` : ''}`,
      ].join('\n');
    })
    .join('\n\n');

  // Software first: it is the filter architecture recruiters search on.
  const skills = [
    ...new Set([
      ...software,
      ...profile.variants.flatMap((v) => v.keywords),
      ...profile.competencies.flatMap((g) => g.items),
    ]),
  ];

  const document = `# LinkedIn profile pack

<!-- Generated by scripts/build-linkedin.ts from data/profile.yaml. Do not edit by hand:
     re-run \`npm run linkedin\` after changing the profile, or the two will drift apart. -->

Generated from the same source as the site and the CV, so the three cannot contradict each
other. Paste each block into the matching LinkedIn field.

## 1. Headline

Pick the one matching the roles being applied for. Limit ${HEADLINE_LIMIT} characters.

${headlines.map((h) => `- \`${h}\` *(${h.length} chars)*`).join('\n')}

## 2. About

\`\`\`
${about}
\`\`\`

## 3. Experience

${roles || '_No roles in the profile yet._'}

## 4. Projects

LinkedIn's Projects section. Each states her role and credits the team in the same words as the
project page, so nobody comparing the two finds a difference.

${projects}

## 5. Education

${profile.education
  .map((q) => {
    const school = q.awardingBody ?? q.institution;
    const note = q.awardingBody ? ` (studied at ${q.institution})` : '';
    const year = valueOf(q.year) ? ` — ${valueOf(q.year)}` : '';
    return `- **${school}**${note}: ${q.degree}${year}${q.thesis ? `. Thesis: ${q.thesis}` : ''}`;
  })
  .join('\n')}

> Enter the **awarding university** as the school. LinkedIn matches against its own university
> entities, and an unrecognised name loses the alumni connections and recruiter filters.

## 6. Licences and certifications

${
  [
    ...profile.registrations.map(
      (r) => `- **${r.title}** — ${r.body}${valueOf(r.year) ? `, issued ${valueOf(r.year)}` : ''}`,
    ),
    ...profile.certifications.map(
      (c) => `- **${c.title}** — ${c.issuer}${valueOf(c.year) ? `, ${valueOf(c.year)}` : ''}`,
    ),
  ].join('\n') || '_None in the profile yet._'
}

## 7. Skills

Add in this order; the first few carry the most weight in recruiter search.

${skills.map((s, i) => `${i + 1}. ${s}`).join('\n')}

## 8. Settings that matter

- **Open to work** — recruiters only. Job titles: ${[...new Set(profile.variants.flatMap((v) => v.targetTitles))].join(', ')}.
- **Featured** — pin the portfolio site and the portfolio PDF. For an architect, this section is
  the shop window: it is the first place a recruiter sees work rather than words.
- **Custom URL** — claim a clean \`linkedin.com/in/…\`; the default with digits looks unfinished on a CV.
- **Location** — ${person.location.city}, ${person.location.country}.
- **Contact info** — ${person.email} and the portfolio URL.
- **Banner** — one of her own renders or drawings, never the default.
`;

  const outDir = resolve(PROJECT_ROOT, artifactDirs(profile).docs);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'linkedin.md'), document, 'utf8');
  console.log(
    `  ${artifactDirs(profile).docs}/linkedin.md — ${headlines.length} headline(s), ${skills.length} skills\n`,
  );
}

main();
